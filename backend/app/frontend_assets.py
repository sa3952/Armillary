"""Closed source discovery and path validation for frontend releases."""

from __future__ import annotations

import hashlib
import os
from pathlib import Path, PurePosixPath
import stat


MANIFEST_NAME = "frontend-release.json"
DEFAULT_LOCALE_ENTRYPOINT = "zh-TW/index.html"
# Top-level files that live in frontend/ for tooling reasons and must never
# become runtime assets.  `.json` and `.mjs` are both legitimate browser asset
# suffixes, so the suffix allowlist alone does not stop them: package.json
# (for ESLint) would otherwise ship dev tooling as runtime assets and change
# the release digest.  node_modules is excluded by directory below.
EXCLUDED_SOURCE_BASENAMES = frozenset({
    # npm's project settings (engine-strict, the registry): tooling, never served.
    ".npmrc",
    "README.md",
    "eslint.config.mjs",
    "package-lock.json",
    "package.json",
    "surfaces.json",
})
IGNORED_PLATFORM_METADATA = frozenset({".DS_Store"})
EXCLUDED_SOURCE_DIRECTORIES = frozenset({"tests", "node_modules"})
# The media type each runtime suffix is served with, declared rather than
# guessed.  Starlette asks Python's `mimetypes`, which reads the host's
# /etc/mime.types (and its platform equivalents) when one exists, so the same
# release answered `application/xml` for sitemap.xml on a developer machine
# and whatever the container's table said in production; a crawler reads the
# header, not the file name.  Text types name UTF-8 explicitly: every text
# asset is UTF-8, and RFC 9116 requires the parameter for security.txt.  JSON
# has no charset parameter (RFC 8259 §11); it is UTF-8 by definition.
RUNTIME_MEDIA_TYPES = {
    ".avif": "image/avif",
    ".css": "text/css; charset=utf-8",
    ".gif": "image/gif",
    ".html": "text/html; charset=utf-8",
    ".ico": "image/vnd.microsoft.icon",
    ".jpeg": "image/jpeg",
    ".jpg": "image/jpeg",
    ".js": "text/javascript; charset=utf-8",
    ".json": "application/json",
    ".mjs": "text/javascript; charset=utf-8",
    ".otf": "font/otf",
    ".png": "image/png",
    ".svg": "image/svg+xml",
    ".ttf": "font/ttf",
    ".txt": "text/plain; charset=utf-8",
    ".webp": "image/webp",
    ".woff": "font/woff",
    ".woff2": "font/woff2",
    ".xml": "application/xml; charset=utf-8",
}
RUNTIME_SUFFIXES = frozenset(RUNTIME_MEDIA_TYPES)
# The branded page a browser receives for a page address that does not exist.
# It is part of the release, so its bytes are hashed with the
# rest, but it has no address of its own: the static mount refuses it as a
# request path and serves it only as the body of a 404 (backend/app/
# runtime_static.py).  scripts/frontend/build_pages.py generates it from the
# `error_pages` row of frontend/surfaces.json, which must name this output.
NOT_FOUND_PAGE = "zh-TW/404.html"
# The IndexNow ownership key.  It is public by design: an engine that receives a
# submission (scripts/deployment/submit_indexnow.py) fetches
# https://<host>/<key>.txt and accepts the submission only when that file holds
# exactly the key.  build_pages writes the file; changing the key means
# submitting under a key no engine has verified yet.
INDEXNOW_KEY = "bbb6ac30c1952dbb592262ea2656d708"
INDEXNOW_KEY_FILE = f"{INDEXNOW_KEY}.txt"
# Root-level discovery files a release may carry: these names exactly, so no
# other self-named text file at the root is served.
# llms.txt is generated by build_pages from the page titles and descriptions.
ROOT_DISCOVERY_FILES = frozenset({
    INDEXNOW_KEY_FILE,
    "llms.txt",
    "robots.txt",
    # The exported public source places the release's security.txt
    # here, so it travels inside the hashed frontend release.
    "security.txt",
    "sitemap.xml",
})
# The content version of an asset is the first sixteen hexadecimal digits
# (64 bits) of the SHA-256 of its exact bytes.  scripts/frontend/build_pages.py
# writes it into every `?v=`, and the public cache policy grants the one-year
# immutable lifetime only when a request's `?v=` equals the value recomputed
# from the file being served.  One definition for both, so the token
# cannot outlive the bytes it names.  A release manifest carries the full
# digest; this is its prefix, so an operator can check one against the other.
ASSET_CONTENT_VERSION_HEX_DIGITS = 16
# Text formats compressed on the way out: they carry no
# per-request secret and reflect no request input.  The binary formats above
# are already compressed.  The only compressed API body is the chart result
# (backend/app/runtime_static.py says why that is safe).
COMPRESSIBLE_ASSET_SUFFIXES = frozenset({
    ".css",
    ".html",
    ".js",
    ".json",
    ".mjs",
    ".svg",
    ".txt",
    ".xml",
})


def asset_content_version(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()[:ASSET_CONTENT_VERSION_HEX_DIGITS]


def _discovery_asset_is_allowed(entry: Path, *, at_root: bool) -> bool:
    suffix = entry.suffix.casefold()
    if suffix not in {".txt", ".xml"}:
        return True
    return at_root and entry.name in ROOT_DISCOVERY_FILES


def validate_asset_name(name: object) -> str:
    if not isinstance(name, str) or not name or "\\" in name or "\x00" in name:
        raise ValueError("frontend asset name is not a safe relative POSIX path")
    path = PurePosixPath(name)
    if (
        path.is_absolute()
        or path.as_posix() != name
        or any(part in {"", ".", ".."} or part.startswith(".") for part in path.parts)
        or name == MANIFEST_NAME
    ):
        raise ValueError("frontend asset name is not a safe relative POSIX path")
    return name


def discover_source_assets(frontend_directory: Path) -> frozenset[str]:
    frontend = Path(os.path.abspath(frontend_directory))
    metadata = frontend.lstat()
    if not stat.S_ISDIR(metadata.st_mode) or frontend.is_symlink():
        raise ValueError("frontend source must be a non-symlink directory")
    assets: set[str] = set()

    def collect(directory: Path, relative_parent: PurePosixPath | None = None) -> None:
        for entry in sorted(directory.iterdir(), key=lambda item: item.name):
            relative = (
                PurePosixPath(entry.name)
                if relative_parent is None
                else relative_parent / entry.name
            )
            entry_metadata = entry.lstat()
            if entry.is_symlink():
                raise ValueError(f"unsafe frontend source entry: {relative}")
            if stat.S_ISDIR(entry_metadata.st_mode):
                if relative_parent is None and entry.name in EXCLUDED_SOURCE_DIRECTORIES:
                    continue
                if entry.name.startswith("."):
                    raise ValueError(f"unsafe frontend source entry: {relative}")
                collect(entry, relative)
                continue
            if not stat.S_ISREG(entry_metadata.st_mode):
                raise ValueError(f"unsafe frontend source entry: {relative}")
            if entry.name in IGNORED_PLATFORM_METADATA:
                continue
            if relative_parent is None and entry.name in EXCLUDED_SOURCE_BASENAMES:
                continue
            if entry.name.startswith("."):
                raise ValueError(f"unsafe frontend source entry: {relative}")
            name = validate_asset_name(relative.as_posix())
            if entry.suffix.casefold() not in RUNTIME_SUFFIXES:
                raise ValueError(f"unsupported frontend asset: {name}")
            if not _discovery_asset_is_allowed(
                entry,
                at_root=relative_parent is None,
            ):
                raise ValueError(f"unsupported frontend discovery asset: {name}")
            assets.add(name)
    collect(frontend)
    if DEFAULT_LOCALE_ENTRYPOINT not in assets:
        raise ValueError(
            f"frontend release requires {DEFAULT_LOCALE_ENTRYPOINT}"
        )
    return frozenset(assets)


def asset_parent_directories(assets: set[str] | frozenset[str]) -> frozenset[str]:
    parents: set[str] = set()
    for name in assets:
        path = PurePosixPath(validate_asset_name(name))
        for parent in path.parents:
            if parent != PurePosixPath("."):
                parents.add(parent.as_posix())
    return frozenset(parents)
